// Բացել մոդալ պատուհանը համապատասխան բանալիով
function openModal(categoryKey) {
    const modal = document.getElementById('infoModal');
    const titleEl = document.getElementById('modalTitle');
    const textEl = document.getElementById('modalText');

    if (modalData[categoryKey]) {
        titleEl.textContent = modalData[categoryKey].title;
        textEl.textContent = modalData[categoryKey].text;
        modal.style.display = 'flex';
    }
}

// Փակել մոդալ պատուհանը
function closeModal() {
    const modal = document.getElementById('infoModal');
    modal.style.display = 'none';
}

// Փակել պատուհանը, եթե սեղմում ենք դրսի մուգ տարածքի վրա
window.onclick = function(event) {
    const modal = document.getElementById('infoModal');
    if (event.target === modal) {
        modal.style.display = 'none';
    }
}

// Մշակութային ակնարկի տեքստը բացելու/փակելու ֆունկցիա
function toggleAboutSection() {
    const moreText = document.getElementById("moreAboutText");
    const btn = document.getElementById("toggleAboutBtn");

    if (moreText.style.display === "none") {
        moreText.style.display = "block";
        btn.textContent = "Թաքցնել";
    } else {
        moreText.style.display = "none";
        btn.textContent = "Կարդալ ավելին";
    }
}
